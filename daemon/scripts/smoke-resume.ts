// Resume + always-allow + versions: node scripts/smoke-resume.ts <base> <token> <sessionId> <folderAbs>
import WebSocket from "ws";
import fs from "node:fs";
const [base, token, sid, folderAbs] = process.argv.slice(2);
const H = { authorization: `Bearer ${token}`, "content-type": "application/json" };
const api = async (m: string, p: string, b?: unknown) => (await fetch(base + p, { method: m, headers: H, body: b ? JSON.stringify(b) : undefined })).json();
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));
const ok = (c: unknown, m: string) => { if (!c) { console.error("FAIL:", m); process.exit(1); } console.log("ok:", m); };
const w = new WebSocket(base.replace("http", "ws") + "/ws", { headers: { authorization: `Bearer ${token}` } });
await new Promise((r) => w.once("open", r));
const events: any[] = []; let approval: any = null;
w.on("message", (raw) => { const m = JSON.parse(raw.toString()); if (m.sessionId !== sid) return;
  if (m.type === "transcript.event") events.push(m.event); if (m.type === "approval.request") approval = m; });
w.send(JSON.stringify({ type: "subscribe", sessionId: sid }));
w.send(JSON.stringify({ type: "prompt.send", sessionId: sid, text: "What file did you just create? Overwrite it so the title and h1 say 'Hello Hub v2'. Use the Write tool." }));
for (let i = 0; i < 120 && !approval; i++) await wait(500);
ok(approval, "approval after resume: " + approval?.summary);
w.send(JSON.stringify({ type: "approval.respond", requestId: approval.requestId, decision: "always" }));
for (let i = 0; i < 180 && !events.some((e) => e.kind === "result"); i++) await wait(500);
const text = events.filter((e) => e.kind === "assistant").map((e) => e.text).join(" ");
ok(/hello\.html/i.test(text), "resumed context remembered the file");
const local = fs.readFileSync(folderAbs + "/.claude/settings.local.json", "utf8");
ok(/allow/.test(local), "always-allow wrote .claude/settings.local.json: " + local.replace(/\s+/g, " "));
await wait(1500);
const outs = await api("GET", `/outputs?project=${encodeURIComponent(folderAbs)}`);
const page = outs.find((o: any) => o.relpath === "hello.html");
ok(page?.versionCount === 2, `hello.html has 2 versions (title: ${page?.title})`);
const vs = await api("GET", `/outputs/${page.id}/versions`);
const v1 = await (await fetch(`${base}/vfiles/${sid}/${vs[0].id}/hello.html`, { headers: H })).text();
const cur = await (await fetch(`${base}/files/${sid}/hello.html`, { headers: H })).text();
ok(!v1.includes("v2") && cur.includes("v2"), "v1 served from versions, current from project");
const esc = await fetch(`${base}/files/${sid}/..%2F..%2Fetc%2Fpasswd`, { headers: H });
ok(esc.status === 403, "path escape rejected (" + esc.status + ")");
process.exit(0);
